/**
 * Builds the Xhibit AI logo: the "Window" mark and the "xhibit ai" wordmark.
 *
 *   npm run logo      (then `npm run og` to refresh the share images)
 *
 * Mark: a rounded square cut by an X into four tiles, one in each brand hue. The four sides are a frame,
 * the thing on display; the X is how you look through it. Small sizes (favicon) get a wider cut so the
 * colours never blur together.
 * Wordmark: "xhibit" in Plus Jakarta Sans ExtraBold + "ai" in Medium grey, drawn as outlines.
 *
 * Writes: src/components/brand/logo-paths.ts, public/favicon.svg, public/apple-touch-icon.png, public/brand/*
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import opentype from "opentype.js";
import sharp from "sharp";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const f = (n) => +n.toFixed(2);

/* ── Colours ── */
export const HUES = { light: ["#2747e3", "#6a46d9", "#e2501f", "#0e7a55"], dark: ["#8fa3ff", "#b49cff", "#ff8a5c", "#4fd1a1"] };
const INK = "#0b0b0c";
const PORCELAIN = "#f5f5f2";
const DUSK = "#0d0e18";
const GREY = { light: "#8a8a90", dark: "rgba(255,255,255,.5)" };

/* ── Mark geometry (viewBox 0 0 100 100): four triangles between the diagonals, inner corners rounded ── */
function roundedPolygon(pts, r) {
  // Each corner is cut back by r along both edges and joined with a quadratic curve through the vertex.
  const n = pts.length;
  const lerp = (a, b, t) => [a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t];
  const dist = (a, b) => Math.hypot(b[0] - a[0], b[1] - a[1]);
  let d = "";
  for (let i = 0; i < n; i++) {
    const prev = pts[(i - 1 + n) % n];
    const cur = pts[i];
    const next = pts[(i + 1) % n];
    const a = lerp(cur, prev, r / dist(cur, prev));
    const b = lerp(cur, next, r / dist(cur, next));
    d += `${i ? "L" : "M"}${f(a[0])} ${f(a[1])}Q${f(cur[0])} ${f(cur[1])} ${f(b[0])} ${f(b[1])}`;
  }
  return d + "Z";
}
/** s = half the cut, measured along an edge; the visible gap is s·√2·… wide. */
function tiles(s, r = 3.2) {
  const o = 4; // run past the edges; the rounded square clips them
  return [
    roundedPolygon([[s - o, -o], [100 - s + o, -o], [50, 50 - s]], r), // top
    roundedPolygon([[100 + o, s - o], [100 + o, 100 - s + o], [50 + s, 50]], r), // right
    roundedPolygon([[100 - s + o, 100 + o], [s - o, 100 + o], [50, 50 + s]], r), // bottom
    roundedPolygon([[-o, 100 - s + o], [-o, s - o], [50 - s, 50]], r), // left
  ];
}
const TILES = tiles(4.6);
const TILES_SMALL = tiles(7.6, 2.4);
const RADIUS = 23; // corner radius of the square

/* ── Wordmark ── */
const FONT_DIR = path.join(ROOT, "node_modules/@fontsource/plus-jakarta-sans/files");
const load = (file) => {
  const buf = fs.readFileSync(path.join(FONT_DIR, file));
  return opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));
};
const extraBold = load("plus-jakarta-sans-latin-800-normal.woff");
const medium = load("plus-jakarta-sans-latin-500-normal.woff");
function text(font, str, size, tracking = 0) {
  let x = 0;
  const parts = [];
  const glyphs = font.stringToGlyphs(str);
  glyphs.forEach((g, i) => {
    parts.push(g.getPath(x, 0, size).toPathData(2));
    x += (g.advanceWidth / font.unitsPerEm) * size;
    if (i < glyphs.length - 1) x += (font.getKerningValue(g, glyphs[i + 1]) / font.unitsPerEm) * size + tracking;
  });
  return { d: parts.join(" "), width: x, bbox: font.getPath(str, 0, 0, size).getBoundingBox() };
}
const SIZE = 100;
const word = text(extraBold, "xhibit", SIZE, -4.5);
const ai = text(medium, "ai", SIZE, -3);
const ascender = -word.bbox.y1; // top of h and b
const MARK = f(ascender); // the mark is as tall as the ascenders and sits on the baseline
const GAP = f(MARK * 0.26);
const wordX = MARK + GAP - word.bbox.x1;
const aiX = wordX + word.width + 22;
const W = f(aiX + ai.bbox.x2 + 1);
const H = f(MARK + Math.max(word.bbox.y2, ai.bbox.y2, 0) + 1);
const markT = `translate(0 ${f(H - MARK - Math.max(word.bbox.y2, ai.bbox.y2, 0) - 1)}) scale(${f(MARK / 100)})`;
const baseY = f(H - Math.max(word.bbox.y2, ai.bbox.y2, 0) - 1);

fs.writeFileSync(
  path.join(ROOT, "src/components/brand/logo-paths.ts"),
  `/* Generated by scripts/logo.mjs — do not edit by hand. */
/** Mark: viewBox 0 0 100 100, clipped to a rounded square of this radius. Tiles: top, right, bottom, left. */
export const MARK_RADIUS = ${RADIUS};
export const TILES = ${JSON.stringify(TILES)} as const;
/** Wider cuts for favicon-sized marks (under ~32 px), so the colours don't blur together. */
export const TILES_SMALL = ${JSON.stringify(TILES_SMALL)} as const;
export const HUES = ${JSON.stringify(HUES)} as const;
/** Wordmark viewBox and parts (mark scaled to the ascender height, sitting on the baseline). */
export const WORDMARK = { w: ${W}, h: ${H}, markTransform: "${markT}", baseY: ${baseY} } as const;
export const WORD = { x: ${f(wordX)}, d: "${word.d}" } as const;
export const AI = { x: ${f(aiX)}, d: "${ai.d}" } as const;
`,
);

/* ── SVG builders ── */
let uid = 0;
function markSvg(hues, small = false) {
  const id = `m${uid++}`;
  const t = small ? TILES_SMALL : TILES;
  return `<defs><clipPath id="${id}"><rect width="100" height="100" rx="${RADIUS}"/></clipPath></defs><g clip-path="url(#${id})">${t.map((d, i) => `<path d="${d}" fill="${hues[i]}"/>`).join("")}</g>`;
}
const wordmarkSvg = (tone) => {
  const ink = tone === "dark" ? "#ffffff" : INK;
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" width="${f(W * 4)}" height="${f(H * 4)}"><title>Xhibit AI</title><g transform="${markT}">${markSvg(HUES[tone])}</g><g transform="translate(0 ${baseY})"><path transform="translate(${f(wordX)} 0)" d="${word.d}" fill="${ink}"/><path transform="translate(${f(aiX)} 0)" d="${ai.d}" fill="${GREY[tone]}"/></g></svg>`;
};
const standalone = (hues, small = false, size = 400) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100" width="${size}" height="${size}"><title>Xhibit AI</title>${markSvg(hues, small)}</svg>`;
/** Square icon with the mark centred on a plain background (profile pictures crop to a circle). */
const padded = (bg, scale) => {
  const pad = (100 - 100 * scale) / 2;
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100"><rect width="100" height="100" fill="${bg}"/><g transform="translate(${f(pad)} ${f(pad)}) scale(${scale})">${markSvg(HUES.light)}</g></svg>`;
};

/* ── Files ── */
const brand = path.join(ROOT, "public/brand");
fs.mkdirSync(brand, { recursive: true });
const files = {
  "xhibit-ai-logo.svg": wordmarkSvg("light"),
  "xhibit-ai-logo-on-dark.svg": wordmarkSvg("dark"),
  "xhibit-mark.svg": standalone(HUES.light),
  "xhibit-mark-mono.svg": standalone([INK, INK, INK, INK]),
  "xhibit-icon.svg": standalone(HUES.light),
};
for (const [name, svg] of Object.entries(files)) fs.writeFileSync(path.join(brand, name), svg);
fs.writeFileSync(path.join(ROOT, "public/favicon.svg"), standalone(HUES.light, true, 32));

const png = (svg, size, out) => sharp(Buffer.from(svg), { density: 600 }).resize(size, size).png().toFile(out);
await png(padded(PORCELAIN, 0.6), 1024, path.join(brand, "xhibit-profile-1024.png")); // WhatsApp, Instagram, LinkedIn
await png(standalone(HUES.light), 1024, path.join(brand, "xhibit-mark-1024.png"));
await png(padded("#ffffff", 0.7), 180, path.join(ROOT, "public/apple-touch-icon.png")); // iPhone home screen
const wordPng = (svg, bg, out) =>
  sharp({ create: { width: 2400, height: 900, channels: 4, background: bg } })
    .composite([{ input: Buffer.from(svg.replace(/width="[^"]+" height="[^"]+"/, 'width="1700"')), gravity: "center" }])
    .png()
    .toFile(path.join(brand, out));
await wordPng(files["xhibit-ai-logo.svg"], PORCELAIN, "xhibit-ai-logo.png");
await wordPng(files["xhibit-ai-logo-on-dark.svg"], DUSK, "xhibit-ai-logo-on-dark.png");
for (const old of ["xhibit-icon-1024.png"]) fs.rmSync(path.join(brand, old), { force: true });
console.log(`logo: wordmark ${W} × ${H}, brand files in public/brand/`);
